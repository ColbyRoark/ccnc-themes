"""Writes the theme gallery into README.md (between the catalog markers) and docs/CATALOG.md from packs/*/theme.json.

    python3 -I tools/catalog.py
"""
import json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
START, END = '<!-- catalog:start -->', '<!-- catalog:end -->'


def main():
    packs = []
    for d in sorted(os.listdir(os.path.join(ROOT, 'packs'))):
        j = os.path.join(ROOT, 'packs', d, 'theme.json')
        if os.path.isfile(j):
            packs.append((d, json.load(open(j, encoding='utf-8'))))

    def img(d, t):
        return 'preview.png' if os.path.isfile(os.path.join(ROOT, 'packs', d, 'preview.png')) else t.get('wallpaper') or 'wallpaper.jpg'

    def who(t):
        w = t.get('author', '')
        return '[%s](https://github.com/%s)' % (w or '@' + t['github'], t['github']) if t.get('github') else w

    # README: a compact gallery, three per row.
    cells = ['<td width="33%%" align="center"><a href="docs/CATALOG.md#%s"><img src="packs/%s/%s"></a><br><b>%s</b></td>'
             % (d, d, img(d, t), t['name']) for d, t in packs]
    rows = ['<tr>' + ''.join(cells[i:i + 3]) + '</tr>' for i in range(0, len(cells), 3)]
    gallery = '%d themes. Details for each: [docs/CATALOG.md](docs/CATALOG.md).\n\n<table>\n%s\n</table>' % (len(packs), '\n'.join(rows))
    p = os.path.join(ROOT, 'README.md')
    s = open(p, encoding='utf-8').read()
    block = '%s\n%s\n%s' % (START, gallery, END)
    s = re.sub(re.escape(START) + '.*?' + re.escape(END), lambda m: block, s, flags=re.S) if START in s else s + '\n' + block + '\n'
    open(p, 'w', encoding='utf-8').write(s)

    # docs/CATALOG.md: one section per theme.
    out = ['# Theme catalog', '', '[← Back to README](../README.md)', '',
           '<!-- Generated by tools/catalog.py from packs/*/theme.json. Do not edit by hand. -->', '',
           '%d themes. Install them from **Settings > Screen Theme > Theme Store** in ccNC.' % len(packs), '',
           '| Theme | Style | Cars | Version | Author |', '|---|---|---|---|---|']
    for d, t in packs:
        brands = ' + '.join(b.capitalize() for b in t.get('brands', [])) or 'Hyundai + Kia'
        out.append('| [%s](#%s) | %s | %s | %s | %s |' % (t['name'], d, 'Light' if t.get('light') else 'Dark', brands, t.get('version', '1.0'), who(t)))
    for d, t in packs:
        brands = ' + '.join(b.capitalize() for b in t.get('brands', [])) or 'Hyundai + Kia'
        extras = [x for x, k in (('startup video', 'boot_video'), ('custom icons', 'icons')) if t.get(k)]
        out += ['', '<a id="%s"></a>' % d, '## %s' % t['name'], '',
                '<img src="../packs/%s/%s" width="720">' % (d, img(d, t)), '',
                '> %s' % t.get('description', ''), '',
                '| | |', '|---|---|',
                '| ID | `%s` |' % d, '| Style | %s |' % ('Light' if t.get('light') else 'Dark'),
                '| Cars | %s |' % brands, '| Version | %s |' % t.get('version', '1.0'), '| Author | %s |' % who(t)]
        if extras:
            out.append('| Includes | %s |' % ', '.join(extras))
        out.append('| Files | [packs/%s](../packs/%s) |' % (d, d))
    open(os.path.join(ROOT, 'docs', 'CATALOG.md'), 'w', encoding='utf-8').write('\n'.join(out) + '\n')
    print('catalog: %d themes' % len(packs))


if __name__ == '__main__':
    main()
